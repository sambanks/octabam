#!/usr/bin/env python3
"""Build the ColdFire unit `drummer_unit.s` from drummer.c + adapter.c + hooks.s, or --check that the
checked-in copy is current, or --dry to compile only. The engine stays in C; the builder links GNU-as.

Needs m68k-elf-gcc. Reads no firmware.
"""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror']
SOURCES = ('drummer.c', 'autokit.c', 'adapter.c', 'kit.c', 'store.c')
ASM = ('hooks.s', 'machine.s')
# Stock targets the unit may reach besides its own labels: the stubs' returns (0x400a2d88 the
# sequencer tick, 0x4000d3b4 the packer) and the stock FLEX start 0x4000f450.
STOCK_CALLS = {'0x400a2d88', '0x4000d3b4', '0x4000f450', '0x4009dcaa',
               # machine.s: the stock continuations of its detours (ANALOG BD's seams)
               '0x400334de', '0x40079822', '0x400585e6', '0x4003a536', '0x4003cda0',
               '0x40078890', '0x4003d722', '0x4004c374', '0x4003c986', '0x400786ce',
               '0x400786fc', '0x4003d1cc', '0x40027e00', '0x40031ed6', '0x40031ece', '0x40002320',
               '0x4005213c', '0x4007e940', '0x40052228', '0x4003c054', '0x4003c058',
               # kit.c: the window, its drawing, the layers, the track's trig (CHORDS' and SCALES' calls)
               '0x40005030', '0x40012254', '0x40012bd8', '0x40011910', '0x4003146c', '0x40031494',
               '0x400356a8', '0x40055db4', '0x40057c84', '0x4005829c',
               # store.c: STORE's file calls and stock's file copy
               'store_path', 'store_fopen', 'store_fread', 'store_fwrite', 'store_fclose', 'store_crc32',
               'store_refuse', '0x40016388',
               # the kit file: the engine task's receive, its continuations, the queue post
               '0x40000d00', '0x4008484e', '0x4008485e', '0x40000c3c',
               # AUTO: stock's pool walk, the YES/NO box, the toast
               '0x4009499c', '0x4006d57c', '0x4005a2b8',
               # PAGES' locks (hooks.s, HAVE_PAGELOCKS)
               'pg_lk_step', 'pg_lk_value', 'pg_lk_shown', 'pg_lk_where'}
OUT = 'drummer_unit.s'


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found')
    return gcc


def generate():
    gcc = compiler()
    parts = ['| Generated by generate.py from drummer.c, adapter.c and hooks.s.\n'
             '| Edit those; run `python3 generate.py` to refresh this file.\n']
    with tempfile.TemporaryDirectory() as td:
        unit = pathlib.Path(td) / 'drummer_unit.c'
        unit.write_text(''.join(f'#include "{HERE / name}"\n' for name in SOURCES))
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([gcc, *FLAGS, '-I', str(HERE), '-S', unit.name, '-o', str(out)], cwd=td, check=True)
        parts.append('| ---- drummer.c + adapter.c ----\n' + out.read_text())
    for name in ASM:
        parts.append(f'| ---- {name} ----\n' + (HERE / name).read_text())
    return '\n'.join(parts)


def external_calls(source):
    calls = set()
    for line in source.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] in ('jsr', 'jbsr', 'bsr', 'jmp', 'jra', 'bsr.l'):
            target = words[1].split(',')[0].lstrip('(').replace(').l', '').rstrip(')')
            if target.isdigit():
                target = hex(int(target))          # GCC prints a call through a constant in decimal
            if not target.startswith(('.', '%')):
                calls.add(target)
    defined = {m.group(1) for m in re.finditer(r'^([A-Za-z_.$][\w.$]*):', source, re.M)}
    return calls - defined - STOCK_CALLS


def assemble(source):
    with tempfile.TemporaryDirectory() as td:
        src = pathlib.Path(td) / OUT
        src.write_text(source)
        (pathlib.Path(td) / 'remix.inc').write_text('.set HAVE_PAGELOCKS, 1\n')   # manifest.py's drummer_inc
        r = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', str(src),
                            '-o', str(pathlib.Path(td) / 'u.o')], capture_output=True, text=True, cwd=td)
        if r.returncode:
            sys.exit(f'{OUT} does not assemble for the 5475:\n' + r.stderr)


if __name__ == '__main__':
    subprocess.run([sys.executable, str(HERE / 'styles.py')] + (['--check'] if '--check' in sys.argv else []), check=True)
    source = generate()
    stray = external_calls(source)
    if stray:
        sys.exit(f'{OUT} calls outside the unit: {sorted(stray)}')
    if re.search(r'^\s*\.(bss|comm|lcomm)\b', source, re.M):
        sys.exit(f'{OUT} has .bss / common: DRAM .bss is not zeroed on the unit (TRAPS trap-dram-bss)')
    assemble(source)
    dest = HERE / OUT
    if '--dry' in sys.argv:
        print(f'ColdFire compile and assembly OK ({len(source.splitlines())} lines)')
    elif '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit(f'{OUT} is stale: run python3 generate.py')
        print(f'{OUT} matches drummer.c, adapter.c and hooks.s')
    else:
        dest.write_text(source)
        print(f'wrote {dest.name} ({len(source.splitlines())} lines): assembles for the 5475, no library calls')
