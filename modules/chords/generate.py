#!/usr/bin/env python3
"""Build the ColdFire unit `chords_unit.s` from chords.c + adapter.c + hooks.s,
or --check that the checked-in copy is current, or --dry to compile only.
The engine stays in C; the builder links GNU-as.

Needs m68k-elf-gcc. Reads no firmware.
"""

import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror']
SOURCES = ('chords.c', 'adapter.c')
# Stock targets the unit may reach besides its own labels: SCALES' service
# (sc_track, sc_mask, sc_keyboard), STORE's (files, the Part reads); adapter.c's window,
# layer, drawing and MIDI calls (its enum). GCC prints those in decimal: the
# scan reads both.
STOCK_CALLS = {'ms_track', 'mh_get', 'sc_track', 'sc_mask', 'sc_keyboard',
               '0x40012254', '0x40012bd8', '0x40012f30', '0x4003146c', '0x40031494', '0x40035624',
               '0x40055db4', '0x4005829c', '0x40016388', '0x40010bc8',
               'store_path', 'store_fopen', 'store_fread', 'store_fwrite', 'store_fclose', 'store_crc32',
               'store_refuse', 'store_part_ui_context', 'store_part_midi_read',
               '0x4009e9a8', '0x40000c3c', '0x4007e998', '0x400135b0', '0x400131a0',
               '0x40035a00', '0x4003604c', '0x400502d4', '0x4005029c', '0x400444f8', '0x400441fc',
               '0x40013904', '0x4003601a', '0x40035f98', '0x400453e2', '0x40044b7c', '0x400455f2', '0x4004550a', '0x4004400c', '0x400444f8',
               '0x40057c84', '0x400356a8', '0x400128a8', '0x40011910',
               '0x40027e00', '0x4009da20', '0x4005a2b8', '0x4004d948'}


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found (brew install m68k-elf-gcc, or the SDK toolchain)')
    return gcc


def generate():
    gcc = compiler()
    parts = ['| Generated by generate.py from chords.c, adapter.c and hooks.s.\n'
             '| Edit those; run `python3 generate.py` to refresh this file.\n']
    # One translation unit, so GCC's local labels (.L3 ...) never collide.
    with tempfile.TemporaryDirectory() as td:
        unit = pathlib.Path(td) / 'chords_unit.c'
        unit.write_text(''.join(f'#include "{HERE / name}"\n' for name in SOURCES))
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([gcc, *FLAGS, '-I', str(HERE), '-S', unit.name, '-o', str(out)], cwd=td, check=True)
        parts.append('| ---- chords.c + adapter.c ----\n' + out.read_text())
    parts.append('| ---- hooks.s ----\n' + (HERE / 'hooks.s').read_text())
    return '\n'.join(parts)


def external_calls(source):
    calls = set()
    for line in source.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] in ('jsr', 'jbsr', 'bsr', 'jmp', 'jra', 'bsr.l'):
            target = words[1].split(',')[0].lstrip('(').rstrip(')')
            if target.isdigit():
                target = f'{int(target):#010x}'
            if not target.startswith(('.', '%')):
                calls.add(target)
    defined = {m.group(1) for m in re.finditer(r'^([A-Za-z_.$][\w.$]*):', source, re.M)}
    return calls - defined - STOCK_CALLS


def assemble(source):
    """Assemble the whole unit for the 5475, so a stub the ColdFire cannot
    encode fails here and not in the firmware build."""
    with tempfile.TemporaryDirectory() as td:
        src = pathlib.Path(td) / 'chords_unit.s'
        src.write_text(source)
        # The build's remix.inc sets HAVE_SCALES; both forms must assemble.
        (pathlib.Path(td) / 'remix.inc').write_text('.set HAVE_SCALES, 1\n.set HAVE_HARMONY, 1\n.set HAVE_MIDI_SCALES, 1\n.set CH_CLIENT, 8\n')
        result = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', f'-Wa,-I{td}', str(src),
                                 '-o', str(pathlib.Path(td) / 'chords_unit.o')], capture_output=True, text=True)
        if result.returncode:
            sys.exit('chords_unit.s does not assemble for the 5475:\n' + result.stderr)


if __name__ == '__main__':
    source = generate()
    stray = external_calls(source)
    if stray:
        sys.exit(f'chords_unit.s calls outside the unit: {sorted(stray)}')
    assemble(source)
    dest = HERE / 'chords_unit.s'
    if '--dry' in sys.argv:
        print(f'ColdFire compile and assembly OK ({len(source.splitlines())} lines), no calls outside the unit')
    elif '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit('chords_unit.s is stale: run python3 generate.py')
        print('chords_unit.s matches chords.c, adapter.c and hooks.s')
    else:
        dest.write_text(source)
        print(f'wrote {dest.name} ({len(source.splitlines())} lines): assembles for the 5475, no library calls')
