#!/usr/bin/env python3
"""Build the ColdFire unit `machines_unit.s` from machines.c + machines.s, or --check that the
checked-in copy is current. Needs m68k-elf-gcc. Reads no firmware.
"""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror']
OUT = 'machines_unit.s'
# A sample remix.inc for the assembly check: two clients.
SAMPLE_INC = """.set MC_END, 7
mc_count: .long 2
mc_sigs: .long 0, 0
mc_defaults: .long 0, 0
mc_flags: .long 0, 0
mc_pages: .long 0, 0
mc_ticks: .long 0, 0
mc_keeps: .long 0, 0
mc_src_names: .long 0, 0, 0, 0, 0, 0, 0
"""


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found')
    return gcc


def generate():
    with tempfile.TemporaryDirectory() as td:
        out = pathlib.Path(td) / 'machines.s'
        subprocess.run([compiler(), *FLAGS, '-S', str(HERE / 'machines.c'), '-o', str(out)], check=True)
        c = out.read_text()
    return ('| Generated by generate.py from machines.c and machines.s.\n'
            '| Edit those; run `python3 generate.py` to refresh this file.\n'
            '| ---- machines.s ----\n' + (HERE / 'machines.s').read_text()
            + '| ---- machines.c ----\n' + c)


def assemble(source):
    with tempfile.TemporaryDirectory() as td:
        (pathlib.Path(td) / OUT).write_text(source)
        (pathlib.Path(td) / 'remix.inc').write_text(SAMPLE_INC)
        r = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', OUT, '-o', 'u.o'],
                           capture_output=True, text=True, cwd=td)
        if r.returncode:
            sys.exit(f'{OUT} does not assemble for the 5475:\n' + r.stderr)


if __name__ == '__main__':
    source = generate()
    if re.search(r'^\s*\.(bss|comm|lcomm)\b', source, re.M):
        sys.exit(f'{OUT} has .bss / common: DRAM .bss is not zeroed on the unit (TRAPS trap-dram-bss)')
    if re.search(r'^\s*(jsr|jbsr|jmp)\s+_?_', source, re.M):
        sys.exit(f'{OUT} calls a library routine')
    assemble(source)
    dest = HERE / OUT
    if '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit(f'{OUT} is stale: run python3 generate.py')
        print(f'{OUT} matches machines.c and machines.s')
    else:
        dest.write_text(source)
        print(f'wrote {OUT} ({len(source.splitlines())} lines): assembles for the 5475')
