def exp2_tab():
    return [int(round((2.0 ** (k / 384.0)) * (1 << 29))) for k in range(EXP2_N)]


def tc_tab():
    """Q31 one-pole step 1 - exp(-1 / (tau SR)), tau = 0.5 ms x 2^(raw / 12.8): 0.5 ms .. 0.47 s."""
    out = []
    for raw in range(TC_N):
        tau = 0.0005 * 2.0 ** (raw / 12.8)
        out.append(min((1 << 31) - 1, int(round((1.0 - math.exp(-1.0 / (tau * SR))) * (1 << 31)))))
    return out


def lfo_tab():
    """Pitch LFO phase step a sample for rate raw 0..127: CHOMPI's rate law, 0.14 Hz x (65.41 / 0.14)^(raw / 127)."""
    return [int(round(0.14 * (65.41 / 0.14) ** (r / 127.0) / SR * 4294967296.0)) for r in range(128)]


def comp_tab():
    """COMP raw 0..127 -> (drive Q26, makeup Q28). Raw 0 is bypass. Drive 1 .. 20 exponentially; the makeup keeps a
    nominal peak (0.36: four voices) at its level through the cubic soft clip y = x - x^3 / 3 (|x| <= 1)."""
    out = [(0, 0)]
    for r in range(1, 128):
        d = 20.0 ** ((r - 1) / 126.0)
        x = min(1.0, d * 0.36)
        y = x - x ** 3 / 3.0
        out.append((int(round(d * (1 << 26))), int(round(0.36 / y * (1 << 28)))))
    return out


def glide_tab():
    """GLID raw 0..127 -> the glide step per 16-sample call, Q31: 1 / (8 x 80^(raw / 127)). Raw 0 is 1/8 (about 3 ms: the anti-click
    glide), raw 127 about 0.23 s (a time constant: it settles in about a second)."""
    return [int(round((1 << 31) / (8.0 * 80.0 ** (r / 127.0)))) for r in range(128)]


def base_inc():
    return int(round(BASE_HZ / SR * 4294967296.0))


