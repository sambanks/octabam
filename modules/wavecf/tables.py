#!/usr/bin/env python3
"""WAVE's wavetable: eight 1,024-sample frames of int16, then frame 7 again (engine.h: frame + 1 needs no test).

The shapes are modules/wave's (the DSP effect, generate.py): sine, triangle, saw, square, then the
zero-mean pulses 1/4, 1/8, 1/16, 1/32, all at its table amplitude AMP.

    python3 modules/wavecf/tables.py            # rewrites tables.s and wcf_data.c
    python3 modules/wavecf/tables.py --check    # exits 1 when either is not what this makes

wcf_data.c holds the note layer's tables: 2^(k/384) for the pitch (1/32 semitone a step), the attack /
release one-pole steps by knob, and the chord shapes.
"""
import math
import pathlib
import sys

FLEN, NFR = 1024, 8
AMP = 0.45
HERE = pathlib.Path(__file__).resolve().parent


def _q(v):
    return max(-32768, min(32767, int(round(v * 32768.0))))


def frames():
    out = [[_q(AMP * math.sin(2 * math.pi * i / FLEN)) for i in range(FLEN)]]
    tri = []
    for i in range(FLEN):
        t = i if i < 256 else (512 - i if i < 768 else i - 1024)
        tri.append(_q(AMP * t / 256.0))
    out.append(tri)
    out.append([_q(AMP * ((i if i < 512 else i - 1024) / 512.0)) for i in range(FLEN)])
    for w in (.5, .25, .125, .0625, .03125):
        W = int(FLEN * w)
        out.append([_q(AMP) if i < W else _q(-AMP * w / (1 - w)) for i in range(FLEN)])
    out.append(out[-1])
    return out


def text():
    lines = ["| Generated by modules/wavecf/tables.py: eight 1,024-sample frames of int16 (big-endian words),",
             "| then frame 7 again.  Do not edit.", "        .text", "        .even", "        .global wcf_table", "wcf_table:"]
    flat = [s for f in frames() for s in f]
    for k in range(0, len(flat), 16):
        lines.append("        .word   " + ",".join(str(s & 0xffff) for s in flat[k:k + 16]))
    return "\n".join(lines) + "\n"


SR = 44100
EXP2_N = 385                      # 2^(k/384), k = 0..384, Q29 (1.0 .. 2.0 = 2^29 .. 2^30)
BASE_HZ = 130.8127826502993       # TUNE 0: C3 (OCTA-303's: raw 64 = C3)
TC_N = 128

CHORDS = (                        # semitones above the note, four voices; VOIC n plays the first n
    (0, 0, 0, 0), (0, 12, 0, 12), (0, 7, 12, 19), (0, 4, 7, 12), (0, 3, 7, 12), (0, 2, 7, 12), (0, 5, 7, 12),
    (0, 3, 6, 12), (0, 4, 8, 12), (0, 4, 7, 11), (0, 3, 7, 10), (0, 4, 7, 10), (0, 3, 6, 9), (0, 3, 6, 10),
    (0, 4, 7, 9), (0, 3, 7, 9), (0, 4, 7, 14), (0, 3, 7, 14), (0, 4, 7, 17), (0, 5, 10, 15), (0, 7, 14, 21),
    (0, 7, 12, 16), (0, 5, 12, 17), (0, 4, 11, 14), (0, 3, 10, 14), (0, 4, 10, 14), (0, 2, 4, 7), (0, 3, 5, 7),
    (0, 2, 7, 9), (0, 7, 10, 14), (0, 4, 9, 14), (0, 12, 19, 24))
CHORD_NAMES = ("UNI", "OCT", "PWR", "MAJ", "MIN", "SUS2", "SUS4", "DIM", "AUG", "MAJ7", "MIN7", "DOM7", "DIM7",
               "M7B5", "MAJ6", "MIN6", "ADD9", "MADD9", "ADD11", "QRT", "5TH", "OPEN", "SPRD", "LYD", "DOR", "MIX",
               "PNT", "PNTM", "6/9", "M9", "M6/9", "STCK")


def exp2_tab():
    return [int(round((2.0 ** (k / 384.0)) * (1 << 29))) for k in range(EXP2_N)]


def tc_tab():
    """Q31 one-pole step 1 - exp(-1 / (tau SR)), tau = 0.5 ms x 2^(raw / 12.8): 0.5 ms .. 0.47 s."""
    out = []
    for raw in range(TC_N):
        tau = 0.0005 * 2.0 ** (raw / 12.8)
        out.append(min((1 << 31) - 1, int(round((1.0 - math.exp(-1.0 / (tau * SR))) * (1 << 31)))))
    return out


def base_inc():
    return int(round(BASE_HZ / SR * 4294967296.0))


def text_c():
    assert len(CHORDS) == 32 and all(len(c) == 4 for c in CHORDS)
    L = ["/* Generated by modules/wavecf/tables.py.  Do not edit. */", "#include <stdint.h>", "",
         f"const uint32_t wcf_base_inc = {base_inc()}u;   /* TUNE 0 (C3) at {SR} Hz */",
         f"const int32_t wcf_exp2[{EXP2_N}] = {{"]
    t = exp2_tab()
    L += ["    " + ", ".join(str(v) for v in t[k:k + 8]) + "," for k in range(0, len(t), 8)] + ["};",
                                                                                          f"const int32_t wcf_tc[{TC_N}] = {{"]
    t = tc_tab()
    L += ["    " + ", ".join(str(v) for v in t[k:k + 8]) + "," for k in range(0, len(t), 8)] + ["};",
                                                                                          "const int8_t wcf_chord[32][4] = {"]
    L += ["    {" + ", ".join(str(v) for v in c) + "}," for c in CHORDS] + ["};", ""]
    return "\n".join(L)


if __name__ == "__main__":
    p, c = HERE / "tables.s", HERE / "wcf_data.c"
    if "--check" in sys.argv:
        sys.exit(0 if p.exists() and p.read_text() == text() and c.exists() and c.read_text() == text_c() else 1)
    p.write_text(text())
    c.write_text(text_c())
    print(f"{p}: {len(frames())} frames; {c}")
