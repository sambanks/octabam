FLEN, NFR = 1024, 8
AMP = 0.45
HERE = pathlib.Path(__file__).resolve().parent


def _q(v):
    return max(-32768, min(32767, int(round(v * 32768.0))))


def frames():
    out = [[_q(AMP * math.sin(2 * math.pi * i / FLEN)) for i in range(FLEN)]]
    tri = []
    for i in range(FLEN):
        t = i if i < 256 else (512 - i if i < 768 else i - 1024)
        tri.append(_q(AMP * t / 256.0))
    out.append(tri)
    out.append([_q(AMP * ((i if i < 512 else i - 1024) / 512.0)) for i in range(FLEN)])
    for w in (.5, .25, .125, .0625, .03125):
        W = int(FLEN * w)
        out.append([_q(AMP) if i < W else _q(-AMP * w / (1 - w)) for i in range(FLEN)])
    out.append(out[-1])
    return out


def text():
    lines = ["| Generated by modules/wavecf/tables.py: eight 1,024-sample frames of int16 (big-endian words),",
             "| then frame 7 again.  Do not edit.", "        .text", "        .even", "        .global wcf_table", "wcf_table:"]
    flat = [s for f in frames() for s in f]
    for k in range(0, len(flat), 16):
        lines.append("        .word   " + ",".join(str(s & 0xffff) for s in flat[k:k + 16]))
    return "\n".join(lines) + "\n"


