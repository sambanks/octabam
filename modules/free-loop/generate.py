#!/usr/bin/env python3
"""Build the ColdFire unit `free_loop.s` from freeloop.c + adapter.c +
hooks.s, or --check that the checked-in copy is current, or --dry to
compile only. The engine stays in C; the builder links GNU-as.

Needs m68k-elf-gcc (Homebrew's bottle or the SDK toolchain). Reads no
firmware.
"""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror']
SOURCES = ('freeloop.c', 'adapter.c')
# Stock targets the unit may reach besides its own labels: the detour
# stubs' returns (0x4000e7a4, 0x4009da16, 0x4009d9ae, 0x40056c2e, 0x40006d20), the CC
# handler's stock calls (0x40001854 the channel map,
# 0x40033970 the auto guard, 0x4009a404 / 0x400a1030 the cue) and STORE's
# file calls; and the stock routines adapter.c calls through FN (its enums:
# the recorder mailbox, MIDI Start / Stop, the drawing calls, the file copy,
# CLEAR SLOT, the layers, the window, the toast, the tempo). GCC prints
# those in decimal: the scan reads both.
STOCK_CALLS = {'0x4000e7a4', '0x4009da16', '0x4009d9ae', '0x40056c2e', '0x40006d20', '0x40001854', '0x40033970',
               '0x4009a404', '0x400a1030', 'store_path', 'store_fopen', 'store_fread', 'store_fwrite',
               'store_fclose', 'store_crc32', 'store_refuse',
               '0x40005178', '0x4000a1e0', '0x4000a274', '0x40011910', '0x40012254', '0x40012bd8',
               '0x40012f30', '0x40016388', '0x4002557c', '0x4003146c', '0x40031494', '0x40035624',
               '0x40055db4', '0x40056f4c', '0x4005829c', '0x4005a2b8', '0x4009c708', '0x400053d8',
               '0x40033e3c', '0x4004c012', '0x4004c024', '0x4004c02a',   # CC_SEND; the edge renderer's draw, blit, skip
               '0x40008f84', '0x4009d3a6', '0x4009d91a',   # RELEASE; the record builder's trig, no-trig exits
               'rtm_gate', 'rtm_draw'}   # REC_TRIG_MUTE's, beside it under HOOKS (HK_REC_GATE / HK_ICON_DRAW)


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found (brew install m68k-elf-gcc, or the SDK toolchain)')
    return gcc


def generate():
    gcc = compiler()
    parts = ['| Generated by generate.py from freeloop.c, adapter.c and hooks.s.\n'
             '| Edit those; run `python3 generate.py` to refresh this file.\n']
    # One translation unit, so GCC's local labels (.L3 ...) never collide.
    with tempfile.TemporaryDirectory() as td:
        unit = pathlib.Path(td) / 'free_loop_unit.c'
        unit.write_text(''.join(f'#include "{HERE / name}"\n' for name in SOURCES))
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([gcc, *FLAGS, '-I', str(HERE), '-S', unit.name, '-o', str(out)], cwd=td, check=True)
        parts.append('| ---- freeloop.c + adapter.c ----\n' + out.read_text())
    parts.append('| ---- hooks.s ----\n' + (HERE / 'hooks.s').read_text())
    return '\n'.join(parts)


def external_calls(source):
    calls = set()
    for line in source.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] in ('jsr', 'jbsr', 'bsr', 'jmp', 'jra', 'bsr.l'):
            target = words[1].split(',')[0].lstrip('(').rstrip(')')
            if target.isdigit():
                target = f'{int(target):#010x}'
            if not target.startswith(('.', '%')):
                calls.add(target)
    defined = {m.group(1) for m in re.finditer(r'^([A-Za-z_.$][\w.$]*):', source, re.M)}
    return calls - defined - STOCK_CALLS


def assemble(source):
    """Assemble the whole unit for the 5475, so a stub the ColdFire cannot
    encode fails here and not in the firmware build."""
    with tempfile.TemporaryDirectory() as td:
        src = pathlib.Path(td) / 'free_loop.s'
        src.write_text(source)
        result = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', str(src),
                                 '-o', str(pathlib.Path(td) / 'free_loop.o')], capture_output=True, text=True)
        if result.returncode:
            sys.exit('free_loop.s does not assemble for the 5475:\n' + result.stderr)


if __name__ == '__main__':
    source = generate()
    stray = external_calls(source)
    if stray:
        sys.exit(f'free_loop.s calls outside the unit: {sorted(stray)}')
    assemble(source)
    dest = HERE / 'free_loop.s'
    if '--dry' in sys.argv:
        print(f'ColdFire compile and assembly OK ({len(source.splitlines())} lines), no calls outside the unit')
    elif '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit('free_loop.s is stale: run python3 generate.py')
        print('free_loop.s matches freeloop.c, adapter.c and hooks.s')
    else:
        dest.write_text(source)
        print(f'wrote {dest.name} ({len(source.splitlines())} lines): assembles for the 5475, no library calls')
