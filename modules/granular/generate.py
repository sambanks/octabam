#!/usr/bin/env python3
"""Generate the linked ColdFire unit from granular.c."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = [
    "-mcpu=5475", "-msoft-float", "-O2", "-ffreestanding", "-fno-builtin",
    "-fno-common", "-fno-jump-tables", "-fno-asynchronous-unwind-tables",
    "-fno-ident", "-fomit-frame-pointer", "-fno-zero-initialized-in-bss",
    "-Wall", "-Wextra", "-Werror",
]


def main():
    check = "--check" in sys.argv
    with tempfile.TemporaryDirectory() as temp_dir:
        generated = pathlib.Path(temp_dir) / "granular.s"
        subprocess.run(
            ["m68k-elf-gcc", *FLAGS, "-S", str(HERE / "granular.c"), "-o", str(generated)],
            check=True,
        )
        body = "| Generated by generate.py; edit granular.c.\n" + generated.read_text()
    output = HERE / "granular.s"
    if check:
        if not output.exists() or output.read_text() != body:
            raise SystemExit(f"stale: {output}")
        print("Granular generated source matches")
    else:
        output.write_text(body)
        print("Granular source generated")


if __name__ == "__main__":
    main()
