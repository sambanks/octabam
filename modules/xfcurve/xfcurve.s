| XF CURVE -- a DRAM unit entered by a jsr at each crossfader handler's
| weight rebuild (0x40061e34 panel, 0x400626ae MIDI CC 48).
|
| Stock maps the crossfader position xf (0..127, 127 = scene A) through a
| 128-entry signed-short table at 0x400bcd90: w = -32768 * share of A, linear
| (w[x] = -round(32768 x / 127)). Every reader of the position goes through
| that table: the two handlers' per-track weights 0x80003c60.. (read by the
| frame builder's scene morph and XVOL every frame), the STRT/LEN/RATE morph
| (0x4003f1b4 and its siblings), MORPH's own weights. So one table is the
| whole curve.
|
| xfc_hook replays the displaced `lea 0x80003c60,%a0`, and before that, when
| the CURVE setting differs from the curve last written, copies that curve's
| 256 bytes over the stock table. LINEAR is stock's table, generated by the
| same formula, so choosing LINEAR again restores stock exactly. The setting
| is read through the BRAIN value table (`get_curve`, remix.inc), so a change
| in the menu lands on the next crossfader move. Clobbers nothing.

        .include "remix.inc"            | get_curve, xfc_n, xfc_tables

        .set    CURVE,   0x400bcd90     | stock: short per xf 0..127
        .set    WEIGHTS, 0x80003c60     | stock: per-track A/B weight longs

        .text
        .globl  xfc_hook
xfc_hook:
        lea     -16(%sp),%sp
        movem.l %d0-%d1/%a0-%a1,(%sp)
        get_curve %d0
        cmp.l   xfc_applied,%d0
        beq.s   1f
        cmpi.l  #xfc_n,%d0              | out of range: leave the table as it is
        bcc.s   1f
        move.l  %d0,xfc_applied
        moveq   #8,%d1
        lsl.l   %d1,%d0                 | 256 bytes a curve
        lea     xfc_tables,%a0
        adda.l  %d0,%a0
        lea     CURVE,%a1
        moveq   #64,%d1                 | 64 longs = 128 shorts
2:      move.l  (%a0)+,(%a1)+
        subq.l  #1,%d1
        bne.s   2b
1:      movem.l (%sp),%d0-%d1/%a0-%a1
        lea     16(%sp),%sp
        lea     WEIGHTS,%a0             | displaced
        rts

        .data
        .balign 4
xfc_applied:
        .long   0                       | the boot table is stock's, LINEAR
