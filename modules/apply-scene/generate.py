#!/usr/bin/env python3
"""Build the ColdFire unit `apply_unit.s` from apply.c + adapter.c + hooks.s,
or --check that the checked-in copy is current, or --dry to compile only.
The engine stays in C; the builder links GNU-as.

Needs m68k-elf-gcc. Reads no firmware.
"""

import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-Os', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror',
         '-fno-auto-inc-dec']
# -Os: about 2.9 KB less than -O2 (8.8 KB of text at -O2 with page 2); everything runs in key handlers,
# where speed does not matter.
# -fno-auto-inc-dec: GCC 16 compiled a copy loop to `move.b (%a0)+,(%a0,%d0.l)`, its
# destination offset counted from a0 before the increment; the port (Musashi) takes
# the incremented a0, so every byte landed one place on. No (An)+ source with An in
# the destination is left to either reading: ambiguous() refuses the form.
SOURCES = ('apply.c', 'adapter.c')
# Stock targets the unit may reach besides its own labels (adapter.c's enum;
# GCC prints them in decimal, the scan reads both).
STOCK_CALLS = {'0x40054cd8', '0x40027e00', '0x4009da20', '0x400418e0', '0x40027de4', '0x4004d948',
               '0x400339d8', '0x4009b2b0', '0x40002df4', '0x4005a2b8', '0x40052a18', '0x40052944',
               '0x4004348c', 'p2s_changed'}
# A stand-in remix.inc for the assembly check: the build writes the real one
# (manifest.py keys_inc) with the settings' reads and the scene keys' tables.
FAKE_INC = ('        .macro  get_tracks reg\n        move.l  #0,\\reg\n        .endm\n'
            '        .set    APS_P2, 0\n        .set    APS_DESC2, 0x400d5fdc\n'
            '        .data\n        .globl  aps_keys_a, aps_keys_b\naps_keys_a:\naps_keys_b:\n'
            '        .byte   0xff, 0\n        .long   0, 0, 0, 0, 0, 0\n        .text\n')


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found (brew install m68k-elf-gcc, or the SDK toolchain)')
    return gcc


def generate():
    gcc = compiler()
    parts = ['| Generated by generate.py from apply.c, adapter.c and hooks.s.\n'
             '| Edit those; run `python3 generate.py` to refresh this file.\n']
    # One translation unit, so GCC's local labels (.L3 ...) never collide.
    with tempfile.TemporaryDirectory() as td:
        unit = pathlib.Path(td) / 'apply_unit.c'
        unit.write_text(''.join(f'#include "{HERE / name}"\n' for name in SOURCES))
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([gcc, *FLAGS, '-I', str(HERE), '-S', unit.name, '-o', str(out)], cwd=td, check=True)
        parts.append('| ---- apply.c + adapter.c ----\n' + out.read_text())
    parts.append('| ---- hooks.s ----\n' + (HERE / 'hooks.s').read_text())
    return '\n'.join(parts)


def external_calls(source):
    calls = set()
    for line in source.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] in ('jsr', 'jbsr', 'bsr', 'jmp', 'jra', 'bsr.l'):
            target = words[1].split(',')[0].lstrip('(').rstrip(')')
            if target.isdigit():
                target = f'{int(target):#010x}'
            if not target.startswith(('.', '%')):
                calls.add(target)
    defined = {m.group(1) for m in re.finditer(r'^([A-Za-z_.$][\w.$]*):', source, re.M)}
    return calls - defined - STOCK_CALLS


def ambiguous(source):
    """Instructions whose (An)+ or -(An) source shares An with the destination."""
    out = []
    for line in source.splitlines():
        m = re.search(r'(?:\((%a\d)\)\+|-\((%a\d)\)),(.*)', line)
        if m and (m.group(1) or m.group(2)) in m.group(3):
            out.append(line.strip())
    return out


def assemble(source):
    """Assemble the whole unit for the 5475, so a stub the ColdFire cannot
    encode fails here and not in the firmware build."""
    with tempfile.TemporaryDirectory() as td:
        src = pathlib.Path(td) / 'apply_unit.s'
        src.write_text(source)
        (pathlib.Path(td) / 'remix.inc').write_text(FAKE_INC)
        result = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', f'-Wa,-I{td}', str(src),
                                 '-o', str(pathlib.Path(td) / 'apply_unit.o')], capture_output=True, text=True)
        if result.returncode:
            sys.exit('apply_unit.s does not assemble for the 5475:\n' + result.stderr)


if __name__ == '__main__':
    source = generate()
    stray = external_calls(source)
    if stray:
        sys.exit(f'apply_unit.s calls outside the unit: {sorted(stray)}')
    odd = ambiguous(source)
    if odd:
        sys.exit(f'apply_unit.s has an (An)+ source with An in the destination: {odd}')
    assemble(source)
    dest = HERE / 'apply_unit.s'
    if '--dry' in sys.argv:
        print(f'ColdFire compile and assembly OK ({len(source.splitlines())} lines), no calls outside the unit')
    elif '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit('apply_unit.s is stale: run python3 generate.py')
        print('apply_unit.s matches apply.c, adapter.c and hooks.s')
    else:
        dest.write_text(source)
        print(f'wrote {dest.name} ({len(source.splitlines())} lines): assembles for the 5475, no library calls')
