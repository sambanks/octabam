#!/usr/bin/env python3
"""Rebuild copyproj.s from copyproj.c + hooks.s, or --check for drift."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer']


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'copyproj.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S',
                        'modules/copy-project/copyproj.c', '-o', str(asm)],
                       cwd=ROOT, check=True)
        return ('| Generated by modules/copy-project/generate.py; edit copyproj.c / hooks.s.\n'
                + asm.read_text() + '\n' + (HERE / 'hooks.s').read_text())


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'copyproj.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('COPY PROJECT copyproj.s is stale: run modules/copy-project/generate.py')
        print('COPY PROJECT ColdFire source matches')
    else:
        dest.write_text(source)
