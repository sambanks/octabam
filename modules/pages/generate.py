#!/usr/bin/env python3
"""Build PAGES' locks unit `locks_unit.s` from locks.c + locks.s, or --check that the checked-in
copy is current. The engine stays in C; the builder links GNU-as (remix.inc gives the clients).

Needs m68k-elf-gcc. Reads no firmware.
"""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror']
OUT = 'locks_unit.s'
# remix.inc's macros, empty, for the assembly check (manifest.py locks_inc writes the real ones)
STUB_INC = '.set PG_CLIENT, 10\n.macro pg_lk_ctx_calls\n.endm\n.macro pg_lk_shown_calls\n.endm\n.macro pg_lk_by_page name\n.endm\n.macro pg_lk_holds\n.space 8\n.endm\n'


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found')
    return gcc


def generate():
    parts = ['| Generated by generate.py from locks.c and locks.s.\n'
             '| Edit those; run `python3 generate.py` to refresh this file.\n']
    with tempfile.TemporaryDirectory() as td:
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([compiler(), *FLAGS, '-S', str(HERE / 'locks.c'), '-o', str(out)], cwd=td, check=True)
        parts.append('| ---- locks.c ----\n' + out.read_text())
    parts.append('| ---- locks.s ----\n' + (HERE / 'locks.s').read_text())
    return '\n'.join(parts)


def assemble(source):
    with tempfile.TemporaryDirectory() as td:
        (pathlib.Path(td) / 'remix.inc').write_text(STUB_INC)
        src = pathlib.Path(td) / OUT
        src.write_text(source)
        r = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', '-I', td, str(src),
                            '-o', str(pathlib.Path(td) / 'u.o')], capture_output=True, text=True, cwd=td)
        if r.returncode:
            sys.exit(f'{OUT} does not assemble for the 5475:\n' + r.stderr)


if __name__ == '__main__':
    source = generate()
    if re.search(r'^\s*\.(bss|comm|lcomm)\b', source, re.M):
        sys.exit(f'{OUT} has .bss / common: DRAM .bss is not zeroed on the unit (TRAPS trap-dram-bss)')
    assemble(source)
    dest = HERE / OUT
    if '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit(f'{OUT} is stale: run python3 generate.py')
        print(f'{OUT} matches locks.c and locks.s')
    else:
        dest.write_text(source)
        print(f'wrote {dest.name} ({len(source.splitlines())} lines): assembles for the 5475')
