#!/usr/bin/env python3
"""Build a module's ColdFire unit from C and GNU-as, the way every C module does.

A module that keeps its engine in C (chords, free-loop, drummer, pages,
machines) checks in one generated `.s`: GCC's output for its C sources,
compiled as ONE translation unit (so GCC's local labels .L3 ... never
collide), followed by its hand-written `.s` files. Its `generate.py`
declares a `Unit` and calls `main(unit)`:

    python3 generate.py            write the unit
    python3 generate.py --check    fail when the checked-in unit is stale
    python3 generate.py --dry      compile and check, write nothing

Before anything is written or compared, the unit must:
  * call nothing outside itself but `stock_calls` (GCC prints a call through
    a constant in decimal: both forms are read); with no `stock_calls`, no
    library routine (`jsr __mulsi3`, `jsr memcpy` ...): a freestanding unit
    links against nothing;
  * have no .bss / common: DRAM .bss is not zeroed on the unit
    (docs/contributing/TRAPS.md, trap-dram-bss);
  * assemble for the 5475 beside `remix_inc`, a sample of what the
    module's manifest writes into remix.inc, so a stub the ColdFire cannot
    encode fails here and not in the firmware build.

Needs m68k-elf-gcc. Reads no firmware. Stdlib only.
"""
import dataclasses
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

FLAGS = ('-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror')
CALLS = ('jsr', 'jbsr', 'bsr', 'jmp', 'jra', 'bsr.l')
LIBRARY = re.compile(r'^_|^(memcpy|memset|memmove|memcmp|strlen|strcpy|strcmp|abort)$')
BSS = re.compile(r'^\s*\.(bss|comm|lcomm)\b', re.M)
LABEL = re.compile(r'^([A-Za-z_.$][\w.$]*):', re.M)


@dataclasses.dataclass(frozen=True)
class Unit:
    """One module's generated unit. `here` is the module directory; `out`
    the checked-in file; `sources` the C files (one translation unit, in
    this order); `asm` the hand-written .s files, after the C unless
    `asm_first`; `stock_calls` the targets outside the unit it may reach
    (None: only the library check); `remix_inc` the sample remix.inc."""
    here: pathlib.Path
    out: str
    sources: tuple
    asm: tuple = ()
    stock_calls: set = None
    remix_inc: str = ''
    asm_first: bool = False

    def names(self):
        files = [*self.sources, *self.asm]
        return files[0] if len(files) == 1 else ', '.join(files[:-1]) + ' and ' + files[-1]


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found (brew install m68k-elf-gcc, or the SDK toolchain)')
    return gcc


def compile_c(unit):
    """GCC's assembly for the unit's C sources, one translation unit. A single
    source compiles as itself; several through a wrapper named after the
    module (`free-loop` -> free_loop_unit.c) that includes each in order."""
    with tempfile.TemporaryDirectory() as td:
        if len(unit.sources) == 1:
            src = str(unit.here / unit.sources[0])
        else:
            src = unit.here.name.replace('-', '_') + '_unit.c'
            (pathlib.Path(td) / src).write_text(''.join(f'#include "{unit.here / n}"\n' for n in unit.sources))
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([compiler(), *FLAGS, '-I', str(unit.here), '-S', src, '-o', str(out)], cwd=td, check=True)
        return out.read_text()


def generate(unit):
    """The unit's full text: the header, the C's assembly, the .s files."""
    c = f'| ---- {" + ".join(unit.sources)} ----\n' + compile_c(unit)
    asm = [f'| ---- {n} ----\n' + (unit.here / n).read_text() for n in unit.asm]
    header = (f'| Generated by generate.py from {unit.names()}.\n'
              '| Edit those; run `python3 generate.py` to refresh this file.\n')
    return '\n'.join([header, *asm, c] if unit.asm_first else [header, c, *asm])


def external_calls(source, stock_calls):
    """Call targets the unit does not define and may not reach: anything
    outside `stock_calls`, or, without them, any library routine."""
    calls = set()
    for line in source.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] in CALLS:
            target = words[1].split(',')[0].lstrip('(').replace(').l', '').rstrip(')')
            if target.isdigit():
                target = f'{int(target):#010x}'
            if not target.startswith(('.', '%')):
                calls.add(target)
    calls -= {m.group(1) for m in LABEL.finditer(source)}
    if stock_calls is None:
        return {c for c in calls if LIBRARY.match(c)}
    return calls - set(stock_calls)


def assemble(unit, source):
    with tempfile.TemporaryDirectory() as td:
        (pathlib.Path(td) / unit.out).write_text(source)
        (pathlib.Path(td) / 'remix.inc').write_text(unit.remix_inc)
        r = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', '-I', td, unit.out, '-o', 'u.o'],
                           capture_output=True, text=True, cwd=td)
        if r.returncode:
            sys.exit(f'{unit.out} does not assemble for the 5475:\n' + r.stderr)


def build(unit):
    """The unit's text, refused (sys.exit) when it breaks a rule above."""
    source = generate(unit)
    stray = external_calls(source, unit.stock_calls)
    if stray:
        sys.exit(f'{unit.out} calls outside the unit: {sorted(stray)}')
    if BSS.search(source):
        sys.exit(f'{unit.out} has .bss / common: DRAM .bss is not zeroed on the unit (TRAPS trap-dram-bss)')
    assemble(unit, source)
    return source


def main(unit, argv=None):
    argv = sys.argv[1:] if argv is None else argv
    source = build(unit)
    dest = unit.here / unit.out
    if '--dry' in argv:
        print(f'ColdFire compile and assembly OK ({len(source.splitlines())} lines), no calls outside the unit')
    elif '--check' in argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit(f'{unit.out} is stale: run python3 generate.py')
        print(f'{unit.out} matches {unit.names()}')
    else:
        dest.write_text(source)
        print(f'wrote {unit.out} ({len(source.splitlines())} lines): assembles for the 5475, no library calls')
