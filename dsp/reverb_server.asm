        move    x:(r7+$54),x0           ; allpass B: b still holds (2048 - tap)
        move    b,a
        sub     x0,a
        move    #>$1,x0
        sub     x0,a
        move    a,n5
        move    r1,a
        and     #>$3ff,a
        move    x:(r7+$5f),x0           ; base B
        add     x0,a
        move    a,r5
        move    x:(r7+$5c),b            ; spaces the r5 write
        move    y:(r5+n5),a
        move    a,x:(r7+$5d)
        move    #>$7ff,m5               ; v100: back to the diffusers' 2048

        do      n7,>rvend

